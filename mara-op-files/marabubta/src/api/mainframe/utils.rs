/// Translates a raw EBCDIC (CP037) byte slice to a UTF-8 String.
pub fn ebcdic_to_utf8(data: &[u8]) -> String {
    data.iter()
        .map(|&b| EBCDIC_TO_ASCII[b as usize] as char)
        .collect()
}

/// Swaps the endianness of a 16-bit integer (IBM Big-Endian to Little-Endian).
pub fn bswap_16(val: u16) -> u16 {
    val.swap_bytes()
}

/// Swaps the endianness of a 32-bit integer (IBM Big-Endian to Little-Endian).
pub fn bswap_32(val: u32) -> u32 {
    val.swap_bytes()
}

/// Swaps the endianness of a 64-bit integer (IBM Big-Endian to Little-Endian).
pub fn bswap_64(val: u64) -> u64 {
    val.swap_bytes()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_ebcdic_to_utf8_basic() {
        // EBCDIC "HELLO"
        let ebcdic = [0xC8, 0xC5, 0xD3, 0xD3, 0xD6];
        assert_eq!(ebcdic_to_utf8(&ebcdic), "HELLO");
    }

    #[test]
    fn test_bswap_32() {
        // Big-endian 1000: 00 00 03 E8
        let val: u32 = 0x000003E8;
        // On x86 (little-endian), this is stored as E8 03 00 00
        // We swap it to get the correct numerical value if interpreted as big-endian
        assert_eq!(bswap_32(val), 0xE8030000);
    }
}
